// Build only the Lucide glyphs the interface uses from the licensed, pinned catalogue.
import {readFileSync,writeFileSync,readdirSync} from 'node:fs';
import {UI_ICON_NAMES} from '../../src/ui-icon-map.js';
const root=new URL('../../',import.meta.url),source=JSON.parse(readFileSync(new URL('icon-sets/lucide.json',root),'utf8'));
const names=new Set(Object.values(UI_ICON_NAMES));
for(const name of readdirSync(new URL('src/',root)).filter(n=>n.endsWith('.js')&&n!=='lucide-ui-data.js')){
  for(const match of readFileSync(new URL(`src/${name}`,root),'utf8').matchAll(/lucide(?:Icon|Body)\('([^']+)'/g))names.add(match[1]);
}
const catalogue=new Map(source.icons.map(i=>[i[0],i[3]])),data={};
for(const name of [...names].sort()){if(!catalogue.has(name))throw new Error(`Unknown Lucide icon: ${name}`);data[name]=catalogue.get(name);}
const text=`// Generated by tools/icons/build-ui.mjs from icon-sets/lucide.json. ISC/Feather MIT; see NOTICE.\nexport const LUCIDE_VERSION=${JSON.stringify(source.version)};\nexport const LUCIDE_GLYPHS=${JSON.stringify(data,null,2)};\n`;
const target=new URL('src/lucide-ui-data.js',root);
if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==text)throw new Error('Lucide UI subset is stale. Run node tools/icons/build-ui.mjs.');}else writeFileSync(target,text);
